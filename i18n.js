  const textOriginals = new WeakMap();
  const originalTitle = document.title;
  let applying = false;

  function normalize(text) {
    return text.replace(/\u00a0/g, ' ').replace(/\s+/g, ' ').trim();
  }

  function translateValue(value, lang) {
    if (!value || lang === DEFAULT_LANG) return value;
    const key = normalize(value);
    const direct = dictionaries[lang]?.[key];
    if (direct) return value.replace(key, direct);
    for (const [pattern, replacement] of rules[lang] || []) {
      if (pattern.test(key)) return value.replace(key, key.replace(pattern, replacement));
    }
    return value;
  }

  function translateTextNode(node, lang) {
    if (!normalize(node.nodeValue)) return;
    if (!textOriginals.has(node)) textOriginals.set(node, node.nodeValue);
    const original = textOriginals.get(node);
    const next = lang === DEFAULT_LANG ? original : translateValue(original, lang);
    if (node.nodeValue !== next) node.nodeValue = next;
  }

  function translateAttributes(element, lang) {
    ['placeholder', 'title', 'aria-label'].forEach(attr => {
      if (!element.hasAttribute(attr)) return;
      const key = `i18nOriginal${attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase())}`;
      if (!element.dataset[key]) element.dataset[key] = element.getAttribute(attr);
      const original = element.dataset[key];
      const next = lang === DEFAULT_LANG ? original : translateValue(original, lang);
      if (element.getAttribute(attr) !== next) element.setAttribute(attr, next);
    });
  }

  function shouldSkip(element) {
    return element.closest('script,style,textarea,[data-i18n-ignore],.language-switcher');
  }

  function translateNode(node, lang) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (!shouldSkip(node.parentElement)) translateTextNode(node, lang);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE || shouldSkip(node)) return;
    translateAttributes(node, lang);
    node.childNodes.forEach(child => translateNode(child, lang));
  }

  function applyLanguage(lang) {
    const selected = dictionaries[lang] ? lang : DEFAULT_LANG;
    applying = true;
    document.documentElement.lang = selected;
    document.documentElement.dataset.language = selected;
    document.title = selected === DEFAULT_LANG ? originalTitle : translateValue(originalTitle, selected);
    document.querySelectorAll('.language-switcher select').forEach(select => select.value = selected);
    translateNode(document.body, selected);
    applying = false;
  }

  function injectSwitcher() {
    if (document.querySelector('.language-switcher')) return;
    const switcher = document.createElement('label');
    switcher.className = 'language-switcher';
    switcher.dataset.i18nIgnore = 'true';
    switcher.innerHTML = '<span>Language</span><select aria-label="Language"><option value="en">English</option><option value="sq">Shqip</option><option value="mk">Македонски</option></select>';
    switcher.querySelector('select').value = localStorage.getItem(LANG_KEY) || DEFAULT_LANG;
    switcher.querySelector('select').addEventListener('change', event => {
      localStorage.setItem(LANG_KEY, event.target.value);
      applyLanguage(event.target.value);
    });
    document.body.appendChild(switcher);
  }

